//! World-map regions and sections.
//!
//! Rectangles are in the 1280×1024 world-map space used by the client UI
//! (`C_BASEWIDTH` / `C_BASEHEIGHT`). Names, ids, episode bounds, and
//! coordinates are a transcription of the public section table. This file is
//! not server source and does not include textures.

#[derive(Clone, Copy, Debug)]
pub struct WorldMapSection {
    pub id: &'static str,
    pub name: &'static str,
    pub top: u16,
    pub left: u16,
    pub width: u16,
    pub height: u16,
    pub ep_from: f32,
    pub ep_to: f32,
    /// Dungeon marker when the source table says `type: 1`. Otherwise 0.
    pub kind: u8,
    /// Shared `index` for stacked dungeon floors. `None` when the table has no
    /// index.
    pub index: Option<u16>,
    /// Optional monster-level label from the table. The show-level toggle is
    /// not drawn.
    pub moblevel: Option<&'static str>,
}

#[derive(Clone, Copy, Debug)]
pub struct WorldMapRegion {
    pub id: &'static str,
    pub name: &'static str,
    pub ep_from: f32,
    pub ep_to: f32,
    pub sections: &'static [WorldMapSection],
}

#[allow(clippy::too_many_arguments)]
const fn section(
    id: &'static str,
    name: &'static str,
    top: u16,
    left: u16,
    width: u16,
    height: u16,
    ep_from: f32,
    ep_to: f32,
) -> WorldMapSection {
    WorldMapSection {
        id,
        name,
        top,
        left,
        width,
        height,
        ep_from,
        ep_to,
        kind: 0,
        index: None,
        moblevel: None,
    }
}

#[allow(clippy::too_many_arguments)]
const fn section_extra(
    id: &'static str,
    name: &'static str,
    top: u16,
    left: u16,
    width: u16,
    height: u16,
    ep_from: f32,
    ep_to: f32,
    kind: u8,
    index: Option<u16>,
    moblevel: Option<&'static str>,
) -> WorldMapSection {
    WorldMapSection {
        id,
        name,
        top,
        left,
        width,
        height,
        ep_from,
        ep_to,
        kind,
        index,
        moblevel,
    }
}

