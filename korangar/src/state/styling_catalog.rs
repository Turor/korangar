//! Stylist catalog in Hercules `db/stylist_db.conf` order.
//!
//! `server_index` is the 1-based index `CZ_REQ_STYLE_CHANGE2` sends. The server
//! does not transmit this list; TEST prices match that file (kRO
//! StylingShopInfo order). `LOOK_BODY2` is omitted: the second costume tab is
//! not drawn.

#[derive(Clone, Copy, Debug)]
pub struct StyleGoods {
    pub server_index: u16,
    pub goods_id: i32,
    pub label: &'static str,
    pub zeny: i32,
    pub item_id: i32,
    pub item_label: &'static str,
    pub box_id: i32,
    pub box_label: &'static str,
    pub allow_doram: bool,
    pub has_doram_cost: bool,
    pub doram_zeny: i32,
    pub doram_item_id: i32,
    pub doram_item_label: &'static str,
    pub doram_box_id: i32,
    pub doram_box_label: &'static str,
}

#[allow(clippy::too_many_arguments)]
const fn goods(
    server_index: u16,
    goods_id: i32,
    label: &'static str,
    zeny: i32,
    item_id: i32,
    item_label: &'static str,
    box_id: i32,
    box_label: &'static str,
    allow_doram: bool,
    has_doram_cost: bool,
    doram_zeny: i32,
    doram_item_id: i32,
    doram_item_label: &'static str,
    doram_box_id: i32,
    doram_box_label: &'static str,
) -> StyleGoods {
    StyleGoods {
        server_index,
        goods_id,
        label,
        zeny,
        item_id,
        item_label,
        box_id,
        box_label,
        allow_doram,
        has_doram_cost,
        doram_zeny,
        doram_item_id,
        doram_item_label,
        doram_box_id,
        doram_box_label,
    }
}

