pub(super) fn static_robe_name(view_id: u16) -> Option<&'static str> {
    ROBE_NAMES.iter().find(|(id, _)| *id == view_id).map(|(_, name)| *name)
}

/// `WeaponNameTable`. Missing rows use `_{view id}`, the same fallback as
/// `getWeaponPath`. View id 0 is not a weapon.
pub(super) fn weapon_file_suffix(view_id: u16) -> String {
    let named = match view_id {
        1 => Some("_단검"),
        2 | 3 => Some("_검"),
        4 | 5 => Some("_창"),
        6 | 7 => Some("_도끼"),
        8 | 9 => Some("_클럽"),
        10 | 23 => Some("_롯드"),
        11 => Some("_활"),
        12 => Some("_너클"),
        13 => Some("_악기"),
        14 => Some("_채찍"),
        15 => Some("_책"),
        16 => Some("_카타르_카타르"),
        17 => Some("_권총"),
        18..=21 => Some("_기관총"),
        22 => Some("_수리검"),
        25 => Some("_단검_단검"),
        26 => Some("_검_검"),
        27 => Some("_도끼_도끼"),
        28 => Some("_단검_검"),
        29 => Some("_단검_도끼"),
        30 => Some("_검_도끼"),
        _ => None,
    };
    match named {
        Some(name) => name.to_owned(),
        None => format!("_{view_id}"),
    }
}

/// `ShieldTable`. An unknown view id uses guard, `ShieldTable[1]`.
pub(super) fn shield_file_name(view_id: u16) -> &'static str {
    match view_id {
        2 => "버클러",
        3 => "쉴드",
        4 => "미러쉴드",
        _ => "가드",
    }
}
